def write_txt_md(path: Path, content: str):
    """写入 txt / md 纯文本"""
    path.write_text(content, encoding="utf-8")


def write_docx(path: Path, title: str, content: str):
    """用 python-docx 生成 Word 文档"""
    from docx import Document

    doc = Document()
    doc.add_heading(title, level=0)

    for raw in content.split("\n"):
        line = raw.rstrip()
        if not line.strip():
            continue
        if line.startswith("# "):
            doc.add_heading(line[2:].strip(), level=1)
        elif line.startswith("## "):
            doc.add_heading(line[3:].strip(), level=2)
        elif line.startswith("- "):
            doc.add_paragraph(line[2:].strip(), style="List Bullet")
        else:
            # 形如 "1. xxx" 的编号项按普通段落处理
            doc.add_paragraph(line.strip())

    doc.save(str(path))


def write_pdf(path: Path, title: str, content: str):
    """用 pymupdf 生成 PDF，中文使用内置 CJK 字体 china-s"""
    import pymupdf

    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)  # A4 竖版
    font = "china-s"
    margin = 50
    page_w = 595 - 2 * margin

    # 标题（居中，大字号）
    page.insert_text((margin, 60), title, fontsize=18, fontname=font)

    # 正文逐段写入，自动换行 + 分页
    y = 90
    line_height = 16
    body = "\n".join(
        line for line in content.split("\n") if not line.startswith("#")
    )

    def emit_line(text: str, fontsize: float):
        nonlocal page, y
        if y + line_height > 842 - margin:
            page = doc.new_page(width=595, height=842)
            y = margin
        page.insert_text((margin, y), text, fontsize=fontsize, fontname=font)
        y += line_height

    for para in body.split("\n"):
        if not para.strip():
            y += 6
            continue
        fontsize = 11
        # 把一段按可用宽度自动换行
        lines = []
        current = ""
        for ch in para:
            if pymupdf.get_text_length(current + ch, fontname=font, fontsize=fontsize) <= page_w:
                current += ch
            else:
                if current:
                    lines.append(current)
                current = ch
        if current:
            lines.append(current)
        for ln in lines:
            emit_line(ln, fontsize)

    doc.save(str(path))


